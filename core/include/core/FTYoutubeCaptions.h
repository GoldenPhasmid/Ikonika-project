#pragma once

#include <cstdint>
#include <string>
#include <vector>

/** One caption line: when it starts, how long it shows, and its text. */
struct FTCaptionCue
{
    int64_t StartMs = 0;
    int64_t DurationMs = 0;
    std::string Text;
};

std::vector<FTCaptionCue> ParseWebVtt(const std::string& Vtt);

struct FTCaptionTrack
{
    std::string LanguageCode;
    std::string BaseUrl;
    bool bAutoGenerated = false;
};

std::vector<FTCaptionTrack> ParseCaptionTrackList(const std::string& WatchPageHtml);

/** Picks which of a video's caption tracks to use: the manual one in the user's language first,
    then an auto-generated one in that language, then any manual one. */
const FTCaptionTrack* PickCaptionTrack(const std::vector<FTCaptionTrack>& Tracks,
                                       const std::string& PreferredLanguage);
